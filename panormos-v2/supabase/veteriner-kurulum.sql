insert into public.vet_ayarlar (id) values (1) on conflict (id) do nothing;
alter table public.vet_ayarlar enable row level security;
grant select on public.vet_ayarlar to anon, authenticated;
grant update on public.vet_ayarlar to authenticated;
drop policy if exists "vet_ayar_okuma" on public.vet_ayarlar;
