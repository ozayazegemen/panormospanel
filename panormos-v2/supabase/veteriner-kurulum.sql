-- Ürünler: herkes aktif ürünleri görür, yönetici düzenler
create table if not exists public.vet_urunler (
  id bigint generated by default as identity primary key,
  ad text not null,
  marka text not null default '',
  kategori text not null default 'kedi',
  fiyat numeric(10,2) not null check (fiyat >= 0),
  eski_fiyat numeric(10,2),
  stok integer,                       -- boş: stok takibi yok
  gorsel text,
  aciklama text not null default '',
  aktif boolean not null default true,
  sira integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.vet_urunler enable row level security;
grant select on public.vet_urunler to anon, authenticated;
grant insert, update, delete on public.vet_urunler to authenticated;
drop policy if exists "vet_urun_okuma" on public.vet_urunler;
create policy "vet_urun_okuma" on public.vet_urunler for select using (aktif = true or public.panel_yoneticisi());
drop policy if exists "vet_urun_yazma" on public.vet_urunler;
create policy "vet_urun_yazma" on public.vet_urunler for all to authenticated
  using (public.panel_yoneticisi()) with check (public.panel_yoneticisi());

